import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss, { type AtRule, type Node as PostcssNode } from 'postcss';

const sourceDirectory = path.dirname(fileURLToPath(import.meta.url));
const styles = readFileSync(path.join(sourceDirectory, 'styles.css'), 'utf8');

const readComponentSource = (directory: string): string => {
  const sources: string[] = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const filePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      sources.push(readComponentSource(filePath));
    } else if (/\.(tsx?|jsx?)$/.test(entry.name) && !/\.test\.(tsx?|jsx?)$/.test(entry.name)) {
      sources.push(readFileSync(filePath, 'utf8'));
    }
  }
  return sources.join('\n');
};

const componentSource = readComponentSource(sourceDirectory);

const root = postcss.parse(styles, { from: 'styles.css' });

const atRuleContext = (node: PostcssNode): string => {
  const context: string[] = [];
  for (let parent = node.parent; parent && parent.type !== 'root'; parent = parent.parent) {
    if (parent.type === 'atrule') {
      const atRule = parent as AtRule;
      if (atRule.name !== 'keyframes') {
        context.unshift(`@${atRule.name} ${atRule.params}`);
      }
    }
  }
  return context.join(' > ');
};

const isExternalClass = (name: string) =>
  name.startsWith('vditor') || name.startsWith('hljs-') || name.startsWith('cm-');

describe('stylesheet structure', () => {
  it('does not retain selectors for removed component classes', () => {
    const removedClasses = [
      'attachments',
      'brand',
      'brand-copy',
      'editor-subrow',
      'editor-switch',
      'editor-toolbar',
      'format-group',
      'list-actions',
      'list-header',
      'list-meta',
      'markdown-editor',
      'markdown-preview',
      'nav-icon',
      'new-note',
      'row-actions',
      'search-box',
      'section-heading',
      'sidebar-footer',
      'sidebar-version',
      'tag-dot',
      'tag-item',
      'tags-heading',
      'tags-input',
    ];
    const selectors: string[] = [];
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      selectors.push(rule.selector);
    });
    for (const name of removedClasses) {
      expect(
        selectors.some((selector) => new RegExp(`\\.${name}(?![\\w-])`).test(selector)),
        `.${name} should not be referenced by CSS`,
      ).toBe(false);
    }
  });

  it('only keeps classes referenced by UI source or generated by Vditor', () => {
    const classes = new Set<string>();
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      for (const match of rule.selector.matchAll(/\.([A-Za-z_][A-Za-z0-9_-]*)/g)) {
        classes.add(match[1]);
      }
    });
    const unreferenced = [...classes]
      .filter((name) => !isExternalClass(name))
      .filter((name) => !new RegExp(`(^|[^A-Za-z0-9_-])${name}([^A-Za-z0-9_-]|$)`).test(componentSource))
      .sort();
    expect(unreferenced).toEqual([]);
  });

  it('does not repeat identical rules in the same cascade context', () => {
    const seen = new Set<string>();
    const duplicates: string[] = [];
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const declarations = rule.nodes
        .filter((node) => node.type === 'decl')
        .map((node) => `${node.prop}|${node.value.replace(/\s+/g, ' ')}|${node.important}`)
        .join(';');
      const key = `${atRuleContext(rule)}||${rule.selector.replace(/\s+/g, ' ')}||${declarations}`;
      if (seen.has(key)) duplicates.push(rule.selector);
      seen.add(key);
    });
    expect(duplicates).toEqual([]);
  });

  it('applies compact note summary styling through CSS', () => {
    const hiddenSelectors = [
      '.note-list.is-compact .note-card time',
      '.note-list.is-compact .note-card p',
      '.note-list.is-compact .note-card-meta',
    ];
    const hiddenRuleSelectors = new Set<string>();
    let compactTitleWeight = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const display = rule.nodes.find(
        (node) => node.type === 'decl' && node.prop === 'display',
      );
      if (display?.type === 'decl' && display.value === 'none') {
        for (const selector of rule.selectors) {
          hiddenRuleSelectors.add(selector.replace(/\s+/g, ' '));
        }
      }
      if (rule.selectors.includes('.note-list.is-compact .note-card-title')) {
        const fontWeight = rule.nodes.find(
          (node) => node.type === 'decl' && node.prop === 'font-weight',
        );
        if (fontWeight?.type === 'decl') compactTitleWeight = fontWeight.value;
      }
    });

    expect([...hiddenRuleSelectors]).toEqual(expect.arrayContaining(hiddenSelectors));
    expect(compactTitleWeight).toBe('400');
  });

  it('forces inactive settings tab panels to stay hidden', () => {
    let hiddenDisplay = '';
    let hiddenDisplayImportant = false;
    root.walkRules((rule) => {
      if (rule.selector.replace(/\s+/g, ' ') !== '.settings-content > [hidden]') return;
      const display = rule.nodes.find(
        (node) => node.type === 'decl' && node.prop === 'display',
      );
      if (display?.type === 'decl') {
        hiddenDisplay = display.value;
        hiddenDisplayImportant = display.important;
      }
    });

    expect(hiddenDisplay).toBe('none');
    expect(hiddenDisplayImportant).toBe(true);
  });

  it('lays out five settings tabs and the source appearance controls', () => {
    const declarationsBySelector = new Map<string, Map<string, string>>();
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const selector = rule.selector.replace(/\s+/g, ' ');
      const declarations = declarationsBySelector.get(selector) ?? new Map<string, string>();
      for (const node of rule.nodes) {
        if (node.type === 'decl') declarations.set(node.prop, node.value);
      }
      declarationsBySelector.set(selector, declarations);
    });

    expect(declarationsBySelector.get('.settings-tabs')?.get('grid-template-columns'))
      .toBe('repeat(5, minmax(0, 1fr))');
    expect(declarationsBySelector.get('.source-color-grid')?.get('grid-template-columns'))
      .toBe('repeat(2, minmax(0, 1fr))');
    expect(componentSource).toContain("color: 'var(--source-foreground)'");
    expect(componentSource).toContain("fontSize: 'var(--source-font-size)'");
    expect(componentSource).toContain("borderLeftWidth: 'var(--source-caret-width)'");
  });

  it('uses a white album background for transparent Mermaid previews', () => {
    const backgrounds = new Map<string, string>();
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const background = rule.nodes.find(
        (node) => node.type === 'decl' && node.prop === 'background',
      );
      if (background?.type === 'decl') {
        backgrounds.set(rule.selector.replace(/\s+/g, ' '), background.value);
      }
    });

    expect(backgrounds.get('.source-line-preview-body.is-mermaid')).toBe('#ffffff');
    expect(backgrounds.get('.source-line-preview-thumbnail-media.is-mermaid'))
      .toBe('#ffffff');
  });

  it('shows every cover variable without pushing properties to the bottom', () => {
    let sizingRuleFound = false;
    root.walkRules((rule) => {
      if (rule.selector.replace(/\s+/g, ' ')
        !== '.settings-modal.is-maximized .pdf-cover-variable-list') return;
      const declarations = new Set(
        rule.nodes
          .filter((node) => node.type === 'decl')
          .map((node) => node.prop + '|' + node.value),
      );
      sizingRuleFound = declarations.has('flex|none') &&
        declarations.has('max-height|none') &&
        declarations.has('min-height|0');
    });
    expect(sizingRuleFound).toBe(true);
  });

  it('keeps the PDF cover preview and inspector independently scrollable', () => {
    const expected = new Map<string, Map<string, string>>();
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const selector = rule.selector.replace(/\s+/g, ' ');
      if (
        selector !== '.pdf-cover-canvas-shell' &&
        selector !== '.pdf-cover-inspector'
      ) {
        return;
      }
      const declarations = expected.get(selector) ?? new Map<string, string>();
      for (const node of rule.nodes) {
        if (node.type === 'decl') declarations.set(node.prop, node.value);
      }
      expected.set(selector, declarations);
    });

    const canvas = expected.get('.pdf-cover-canvas-shell');
    const inspector = expected.get('.pdf-cover-inspector');
    expect(canvas?.get('overflow-y')).toBe('auto');
    expect(canvas?.get('max-height')).toBe('min(56vh, 560px)');
    expect(canvas?.get('scrollbar-gutter')).toBe('stable');
    expect(inspector?.get('overflow-y')).toBe('auto');
    expect(inspector?.get('max-height')).toBe('min(56vh, 560px)');
  });

  it('keeps cover margin guides non-interactive and out of print output', () => {
    let pointerEvents = '';
    let printHidden = false;
    root.walkRules((rule) => {
      if (rule.selector === '.pdf-cover-margin-guide') {
        const declaration = rule.nodes.find(
          (node) => node.type === 'decl' && node.prop === 'pointer-events',
        );
        if (declaration?.type === 'decl') pointerEvents = declaration.value;
      }
      if (
        atRuleContext(rule) === '@media print' &&
        rule.selector === '.pdf-cover-margin-guide'
      ) {
        printHidden = rule.nodes.some(
          (node) => node.type === 'decl' && node.prop === 'display' && node.value === 'none',
        );
      }
    });
    expect(pointerEvents).toBe('none');
    expect(printHidden).toBe(true);
  });

  it('keeps the global search field height stable and its placeholder secondary', () => {
    const declarationsBySelector = new Map<string, Map<string, string>>();
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const selector = rule.selector.replace(/\s+/g, ' ');
      const declarations = declarationsBySelector.get(selector) ?? new Map<string, string>();
      for (const node of rule.nodes) {
        if (node.type === 'decl') declarations.set(node.prop, node.value);
      }
      declarationsBySelector.set(selector, declarations);
    });

    expect(declarationsBySelector.get('.titlebar-search')?.get('height')).toBe('34px');
    expect(
      declarationsBySelector.get('.titlebar-search input::placeholder')?.get('font-size'),
    ).toBe('0.8rem');
    expect(
      declarationsBySelector.get('.titlebar-search .search-clear-button')?.get('height'),
    ).toBe('22px');
  });

  it('keeps editor actions in the footer with a compact hoverable export menu', () => {
    const selectors: string[] = [];
    let headingPadding = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      selectors.push(...rule.selectors.map((selector) => selector.replace(/\s+/g, ' ')));
      if (rule.selectors.includes('.editor-heading')) {
        const padding = rule.nodes.find(
          (node) => node.type === 'decl' && node.prop === 'padding',
        );
        if (padding?.type === 'decl' && padding.value === '8px') {
          headingPadding = padding.value;
        }
      }
    });

    expect(headingPadding).toBe('8px');
    expect(selectors).toEqual(expect.arrayContaining([
      '.editor-footer-actions',
      '.editor-footer-trash',
      '.editor-export-menu button:not(:disabled):hover',
      '.editor-export-menu button:not(:disabled):focus-visible',
      '.editor-find-panel',
      '.editor-find-field',
      '::highlight(puffjoplin-find-match)',
      '::highlight(puffjoplin-find-active)',
    ]));
    expect(selectors.some((selector) => selector.includes('.editor-export-menu small'))).toBe(false);
    expect(componentSource).toContain("exportCurrentNote('markdown')");
    expect(componentSource).toContain("exportCurrentNote('docx')");
    expect(componentSource).toContain("exportCurrentMermaid('svg')");
    expect(componentSource).toContain("exportCurrentMermaid('png')");
    expect(componentSource).toContain('currentMermaidBlocks.length === 0');
    expect(componentSource).not.toContain('可選文字與書籤');
    expect(componentSource).not.toContain('單一自包含檔案');
  });

  it('keeps the Vditor toolbar above the CodeMirror source editor', () => {
    let toolbarZIndex = '';
    let sourceDisplay = '';
    let mirrorPointerEvents = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const declarations = new Map(
        rule.nodes
          .filter((node) => node.type === 'decl')
          .map((node) => [node.prop, node.value]),
      );
      if (rule.selectors.includes('.vditor-editor-host .vditor-toolbar')) {
        toolbarZIndex = declarations.get('z-index') || '';
      }
      if (rule.selectors.includes('.puff-codemirror-source.is-visible')) {
        sourceDisplay = declarations.get('display') || '';
      }
      if (rule.selectors.includes(
        '.vditor-editor-host .vditor-content.is-codemirror-active > .vditor-sv',
      )) {
        mirrorPointerEvents = declarations.get('pointer-events') || '';
      }
    });

    expect(toolbarZIndex).toBe('20');
    expect(sourceDisplay).toBe('flex');
    expect(mirrorPointerEvents).toBe('none');
  });

  it('exposes editor modes as direct toolbar buttons and hides the dropdown controller', () => {
    const wysiwygIndex = componentSource.indexOf("toolbarIconItem('wysiwyg-mode')");
    const instantIndex = componentSource.indexOf("toolbarIconItem('ir-mode')");
    const sourceIndex = componentSource.indexOf("toolbarIconItem('source-mode')");
    expect(wysiwygIndex).toBeGreaterThan(-1);
    expect(instantIndex).toBeGreaterThan(wysiwygIndex);
    expect(sourceIndex).toBeGreaterThan(instantIndex);
    expect(componentSource).toContain("activateEditorMode(editor, 'wysiwyg')");
    expect(componentSource).toContain("activateEditorMode(editor, 'ir')");
    expect(componentSource).toContain("activateEditorMode(editor, 'sv')");

    let controllerDisplay = '';
    let activeBackground = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const declarations = new Map(
        rule.nodes
          .filter((node) => node.type === 'decl')
          .map((node) => [node.prop, node.value]),
      );
      if (rule.selectors.includes('.vditor-editor-host .puff-mode-controller')) {
        controllerDisplay = declarations.get('display') || '';
      }
      if (rule.selectors.some((selector) =>
        selector.includes('button[data-type="wysiwyg-mode"].vditor-menu--current'))) {
        activeBackground = declarations.get('background') || activeBackground;
      }
    });
    expect(controllerDisplay).toBe('none');
    expect(activeBackground).toBe('var(--accent-soft)');
  });

  it('keeps custom mode strokes visible and renders text color directly in red', () => {
    let modeFill = '';
    let modeStroke = '';
    let modeStrokeWidth = '';
    let textColor = '';
    let textColorShadow = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const declarations = new Map(
        rule.nodes
          .filter((node) => node.type === 'decl')
          .map((node) => [node.prop, node.value]),
      );
      if (rule.selectors.some((selector) =>
        selector.includes('data-type="wysiwyg-mode"') &&
        selector.includes('.puff-toolbar-svg'))) {
        modeFill = declarations.get('fill') || modeFill;
        modeStroke = declarations.get('stroke') || modeStroke;
        modeStrokeWidth = declarations.get('stroke-width') || modeStrokeWidth;
      }
      if (rule.selectors.some((selector) =>
        selector.includes('.puff-text-color-toolbar button') &&
        !selector.includes(':hover') &&
        !selector.includes(':focus'))) {
        textColor = declarations.get('color') || textColor;
        textColorShadow = declarations.get('box-shadow') || textColorShadow;
      }
    });

    expect(modeFill).toBe('none');
    expect(modeStroke).toBe('currentColor');
    expect(modeStrokeWidth).toBe('1.8');
    expect(textColor).toBe('#e53935');
    expect(textColorShadow).toBe('none');
  });

  it('keeps the pinned-note affordance icon-only and aligned with the title', () => {
    let activeBackground = '';
    let normalTop = '';
    let compactTop = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const declarations = new Map(
        rule.nodes
          .filter((node) => node.type === 'decl')
          .map((node) => [node.prop, node.value]),
      );
      if (rule.selectors.includes('.icon-button.pin-note-button.active')) {
        activeBackground = declarations.get('background') || '';
      }
      if (rule.selectors.includes('.note-list:not(.is-compact) .icon-button.pin-note-button')) {
        normalTop = declarations.get('top') || '';
      }
      if (rule.selectors.includes('.note-list.is-compact .icon-button.pin-note-button')) {
        compactTop = declarations.get('top') || '';
      }
    });

    expect(activeBackground).toBe('transparent');
    expect(normalTop).toBe('4px');
    expect(compactTop).toBe('1px');
  });

  it('keeps new-note controls icon-only without an accent surface', () => {
    let toolbarBackground = '';
    let toolbarBorder = '';
    let railBackground = '';
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
      const declarations = new Map(
        rule.nodes
          .filter((node) => node.type === 'decl')
          .map((node) => [node.prop, node.value]),
      );
      if (rule.selectors.includes('.note-list-actions .new-note-button')) {
        toolbarBackground = declarations.get('background') || toolbarBackground;
        toolbarBorder = declarations.get('border') || toolbarBorder;
      }
      if (rule.selectors.includes('.icon-button.rail-action.primary-rail')) {
        railBackground = declarations.get('background') || railBackground;
      }
    });

    expect(toolbarBackground).toBe('transparent');
    expect(toolbarBorder).toBe('0');
    expect(railBackground).toBe('transparent');
  });

  it('keeps cascade layer sections in the documented order', () => {
    const requiredSections = [
      'Base layer: design tokens and global reset',
      'Fluent layer: WinUI 3 surface language',
      'Windows shell layer: integrated titlebar and collapsible navigation',
      'Typography layer: configurable type scale',
      'Icon layer: unified system buttons',
      'Fullscreen layer: escape editor containment',
    ];
    const comments: string[] = [];
    root.walkComments((comment) => {
      comments.push(comment.text);
    });
    const positions = requiredSections.map((section) =>
      comments.findIndex((comment) => comment.includes(section)),
    );
    expect(positions).not.toContain(-1);
    expect(positions).toEqual([...positions].sort((left, right) => left - right));
  });
});
